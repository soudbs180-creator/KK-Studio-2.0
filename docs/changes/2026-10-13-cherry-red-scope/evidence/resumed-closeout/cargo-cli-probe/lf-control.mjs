import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { spawnSync, execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
const root = process.cwd();
const directory = path.join(root, '.tmp/cherry-red/cargo-cli-probe');
const probe = path.join(directory, 'old-git-lf-agent');
const git = (...args) => execFileSync('git', ['-C', probe, ...args], { encoding: 'utf8' }).trim();
assert(!fs.existsSync(path.join(probe, '.git')));
git('init', '-q');
git('config', 'core.autocrlf', 'true');
fs.writeFileSync(path.join(probe, '.gitattributes'), 'src-tauri/Cargo.toml text eol=lf\n');
git('add', '.gitattributes', 'src-tauri/Cargo.toml');
const cargo = path.join(probe, 'src-tauri/Cargo.toml');
const before = fs.readFileSync(cargo);
const result = spawnSync(process.execPath, [path.join(root, 'node_modules/@tauri-apps/cli/tauri.js'), 'build', '--config', 'src-tauri/tauri.agent.conf.json', '--config', '{"build":{"beforeBuildCommand":""}}', '--runner', process.execPath, '--no-bundle'], { cwd: probe, encoding: 'utf8', timeout: 30000, windowsHide: true });
assert.equal(result.status, 1);
assert(result.stdout.includes('PROBE_RUNNER_NO_COMPILATION'));
const after = fs.readFileSync(cargo);
assert(before.equals(after));
const status = git('status', '--porcelain', '--untracked-files=no');
assert(!status.split('\n').some(line => line[1] === 'M'));
const receipt = { createdAt: new Date().toISOString(), scope: 'Private LF attribute control only; original source/index untouched; Node runner exits before Rust compilation', coreAutocrlf: git('config', 'core.autocrlf'), attributes: git('check-attr', 'text', 'eol', '--', 'src-tauri/Cargo.toml'), eol: git('ls-files', '--eol', 'src-tauri/Cargo.toml'), beforeSha256: createHash('sha256').update(before).digest('hex'), afterSha256: createHash('sha256').update(after).digest('hex'), privateIndexStatus: status, modifiedWorktreeColumn: false, runnerMarker: true };
fs.writeFileSync(path.join(directory, 'lf-control-receipt.json'), JSON.stringify(receipt, null, 2) + '\n');
console.log(JSON.stringify(receipt));
