type AliasTarget = (typeof aliases)[keyof typeof aliases];
export function withUiIconAliases<T extends Record<AliasTarget, unknown>>(
  icons: T,
) {
  return Object.assign(
    {},
    icons,
    Object.fromEntries(
      Object.entries(aliases).map(([alias, target]) => [alias, icons[target]]),
    ),
  ) as T & { [Key in keyof typeof aliases]: T[(typeof aliases)[Key]] };
}
